"""Generate docs/PERMISSIONS.md and the template snapshot tests/authz/permission_matrix.yaml
from the permission catalogue, role templates and separation-of-duties rules.

uv run python scripts/gen_permissions_doc.py          write both files
uv run python scripts/gen_permissions_doc.py --check  fail if either is out of date
"""

import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from app.authz import catalogue  # noqa: E402
from app.authz.role_templates import TEMPLATES  # noqa: E402

DOC = ROOT / "docs" / "PERMISSIONS.md"
MATRIX = ROOT / "tests" / "authz" / "permission_matrix.yaml"
SCOPE_SHORT = {"self": "S", "team": "T", "department": "D", "organization": "O"}


def render_doc() -> str:
    perms = catalogue.permissions()
    lines = [
        "# Permissions",
        "",
        "<!-- Generated by scripts/gen_permissions_doc.py from each package's policies.py"
        " and app/authz/role_templates.py. Do not edit by hand. -->",
        "",
        "Keys are `module.resource[.sub].action`. A grant has a scope: **Self** (records the"
        " person owns), **Team** (their direct and indirect reports), **Department** (their"
        " department and those under it) or **Organisation**. Records outside a person's"
        " scope answer 404. See ADR 0013.",
        "",
        "## Catalogue",
        "",
    ]
    for module in sorted({p.module for p in perms.values()}):
        lines += [
            f"### {module}",
            "",
            "| Key | Permission | Scopes | Sensitive | Description |",
            "|---|---|---|---|---|",
        ]
        for p in (p for p in perms.values() if p.module == module):
            scopes = ", ".join(s.label for s in p.scopes)
            lines.append(
                f"| `{p.key}` | {p.label} | {scopes} | {'yes' if p.sensitive else ''} "
                f"| {p.description} |"
            )
        lines.append("")
    lines += [
        "## Role templates",
        "",
        "Each installation starts with an editable copy of every template (Super"
        " Administrator excepted: it is protected). Business templates gain grants as their"
        " modules arrive. Scope letters: S self, T team, D department, O organisation.",
        "",
    ]
    for t in TEMPLATES:
        grants = t.resolve()
        flags = [
            f for f, on in (("two-step required", t.requires_mfa), ("protected", t.protected)) if on
        ]
        lines += [
            f"### {t.name}" + (f" ({', '.join(flags)})" if flags else ""),
            "",
            t.description,
            "",
        ]
        if grants:
            lines += ["| Permission | Scope |", "|---|---|"]
            lines += [f"| `{k}` | {SCOPE_SHORT[s.value]} |" for k, s in grants.items()]
        else:
            lines.append("_No grants yet: added by the phase that delivers its module._")
        lines.append("")
    lines += [
        "## Separation of duties",
        "",
        "| Rule | When performing | Blocked if | Message |",
        "|---|---|---|---|",
    ]
    for r in catalogue.sod_rules():
        lines.append(f"| `{r.key}` | `{r.permission}` | {r.conflict} | {r.message} |")
    lines += [
        "",
        "Also enforced in app/authz/service.py: nobody can grant (to a role, a person or a"
        " delegate) a permission they don't hold themselves, or more widely than they hold"
        " it. Delegations last at most the configured number of days (default 90) and"
        " can't include `authz.*` or `system.*` permissions.",
        "",
    ]
    return "\n".join(lines)


def render_matrix() -> str:
    data = {t.key: {k: s.value for k, s in t.resolve().items()} for t in TEMPLATES}
    header = (
        "# Generated by scripts/gen_permissions_doc.py. A change here means a role template's\n"
        "# grants changed: review it, then regenerate.\n"
    )
    return header + yaml.safe_dump(data, sort_keys=True, default_flow_style=False)


def main() -> int:
    outputs = {DOC: render_doc(), MATRIX: render_matrix()}
    if "--check" in sys.argv:
        stale = [
            p for p, c in outputs.items() if not p.exists() or p.read_text(encoding="utf-8") != c
        ]
        for p in stale:
            print(f"{p.relative_to(ROOT)} is out of date. Run: make permissions-doc")
        return 1 if stale else 0
    for path, content in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8", newline="\n")
        print(f"Wrote {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
