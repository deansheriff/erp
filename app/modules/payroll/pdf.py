"""Payslip PDFs (ADR 0021), drawn with reportlab's built-in fonts. They have no naira
sign, so amounts read "NGN 1,250.00"."""

import io
from dataclasses import dataclass
from decimal import Decimal

from reportlab.lib.pagesizes import A4
from reportlab.lib.units import mm
from reportlab.pdfgen.canvas import Canvas

INK = (0.086, 0.086, 0.165)
MUTED = (0.384, 0.384, 0.502)
LINE = (0.894, 0.894, 0.933)


@dataclass(frozen=True, slots=True)
class PayslipDoc:
    organisation: str
    period: str  # "November 2026"
    pay_group: str
    name: str
    number: str | None
    pfa: str | None
    days_paid: int
    days_in_month: int
    earnings: list[tuple[str, str | None, Decimal]]  # (name, detail, amount)
    deductions: list[tuple[str, str | None, Decimal]]
    gross: Decimal
    net: Decimal
    employer: list[tuple[str, Decimal]]  # pension (employer), NSITF
    ytd: list[tuple[str, Decimal]]  # taxable pay, PAYE


def money(amount: Decimal) -> str:
    rounded = amount.quantize(Decimal("0.01"))
    text = f"NGN {abs(rounded):,.2f}"
    return f"({text})" if rounded < 0 else text


def render(doc: PayslipDoc) -> bytes:  # noqa: PLR0915  (one page, drawn top to bottom)
    buffer = io.BytesIO()
    pdf = Canvas(buffer, pagesize=A4)
    pdf.setTitle(f"Payslip {doc.period} - {doc.name}")
    pdf.setAuthor(doc.organisation)
    width, height = A4
    left, right = 20 * mm, width - 20 * mm
    y = height - 22 * mm

    def text(
        x: float,
        value: str,
        *,
        size: float = 10,
        bold: bool = False,
        colour: tuple[float, float, float] = INK,
        align: str = "left",
    ) -> None:
        pdf.setFillColorRGB(*colour)
        pdf.setFont("Helvetica-Bold" if bold else "Helvetica", size)
        if align == "right":
            pdf.drawRightString(x, y, value)
        else:
            pdf.drawString(x, y, value)

    def rule() -> None:
        pdf.setStrokeColorRGB(*LINE)
        pdf.setLineWidth(0.6)
        pdf.line(left, y, right, y)

    text(left, doc.organisation, size=14, bold=True)
    text(right, "Payslip", size=14, bold=True, align="right")
    y -= 7 * mm
    text(left, f"{doc.period} · {doc.pay_group}", colour=MUTED)
    y -= 12 * mm
    text(left, doc.name, size=12, bold=True)
    y -= 5.5 * mm
    details = [doc.number or "", f"PFA: {doc.pfa}" if doc.pfa else ""]
    if doc.days_paid != doc.days_in_month:
        details.append(f"Paid for {doc.days_paid} of {doc.days_in_month} days")
    text(left, "   ".join(d for d in details if d), colour=MUTED)
    y -= 10 * mm

    def section(
        title: str, rows: list[tuple[str, str | None, Decimal]], total_label: str, total: Decimal
    ) -> None:
        nonlocal y
        text(left, title.upper(), size=8, bold=True, colour=MUTED)
        y -= 3 * mm
        rule()
        y -= 5.5 * mm
        for name, detail, amount in rows:
            text(left, name)
            if detail:
                text(left + 70 * mm, detail, size=9, colour=MUTED)
            text(right, money(amount), align="right")
            y -= 6 * mm
        rule()
        y -= 5.5 * mm
        text(left, total_label, bold=True)
        text(right, money(total), bold=True, align="right")
        y -= 11 * mm

    section("Earnings", doc.earnings, "Gross pay", doc.gross)
    section(
        "Deductions",
        doc.deductions,
        "Total deductions",
        sum((a for _, _, a in doc.deductions), Decimal(0)),
    )
    pdf.setFillColorRGB(0.933, 0.925, 0.992)
    pdf.roundRect(left, y - 4 * mm, right - left, 13 * mm, 3 * mm, stroke=0, fill=1)
    y += 0.5 * mm
    text(left + 5 * mm, "Net pay", size=12, bold=True)
    text(right - 5 * mm, money(doc.net), size=12, bold=True, align="right")
    y -= 18 * mm

    for title, rows in (("Paid by your employer", doc.employer), ("Year to date", doc.ytd)):
        text(left, title.upper(), size=8, bold=True, colour=MUTED)
        y -= 3 * mm
        rule()
        y -= 5.5 * mm
        for name, amount in rows:
            text(left, name)
            text(right, money(amount), align="right")
            y -= 6 * mm
        y -= 6 * mm

    y = 15 * mm
    text(
        left, "Generated by Kxmeleon ERP. Keep this payslip for your records.", size=8, colour=MUTED
    )
    pdf.showPage()
    pdf.save()
    return buffer.getvalue()


@dataclass(frozen=True, slots=True)
class CertificateDoc:
    organisation: str
    year: int
    name: str
    number: str | None
    tin: str | None
    state: str | None
    # (month, gross, pension, NHF and NHIS, taxable, PAYE)
    months: list[tuple[str, Decimal, Decimal, Decimal, Decimal, Decimal]]
    rent_relief: Decimal


def render_certificate(doc: CertificateDoc) -> bytes:  # noqa: PLR0915  (one page, top to bottom)
    """A year-end tax deduction certificate: one page, a row per month paid (ADR 0022)."""
    buffer = io.BytesIO()
    pdf = Canvas(buffer, pagesize=A4)
    pdf.setTitle(f"Tax certificate {doc.year} - {doc.name}")
    pdf.setAuthor(doc.organisation)
    width, height = A4
    left, right = 18 * mm, width - 18 * mm
    columns = [left + 55 * mm, left + 85 * mm, left + 113 * mm, left + 143 * mm, right]
    y = height - 22 * mm

    def text(
        x: float,
        value: str,
        *,
        size: float = 9.5,
        bold: bool = False,
        colour: tuple[float, float, float] = INK,
        align: str = "left",
    ) -> None:
        pdf.setFillColorRGB(*colour)
        pdf.setFont("Helvetica-Bold" if bold else "Helvetica", size)
        if align == "right":
            pdf.drawRightString(x, y, value)
        else:
            pdf.drawString(x, y, value)

    def rule() -> None:
        pdf.setStrokeColorRGB(*LINE)
        pdf.setLineWidth(0.6)
        pdf.line(left, y, right, y)

    def row(
        cells: list[str], *, bold: bool = False, colour: tuple[float, float, float] = INK
    ) -> None:
        text(left, cells[0], bold=bold, colour=colour)
        for x, value in zip(columns, cells[1:], strict=True):
            text(x, value, bold=bold, colour=colour, align="right")

    text(left, doc.organisation, size=14, bold=True)
    text(right, "Tax deduction certificate", size=14, bold=True, align="right")
    y -= 7 * mm
    text(left, f"PAYE deducted under the Nigeria Tax Act, tax year {doc.year}", colour=MUTED)
    y -= 12 * mm
    text(left, doc.name, size=12, bold=True)
    y -= 5.5 * mm
    details = [doc.number or "", f"TIN: {doc.tin}" if doc.tin else "", doc.state or ""]
    text(left, "   ".join(d for d in details if d), colour=MUTED)
    y -= 11 * mm

    row(
        ["Month", "Gross pay", "Pension", "NHF, NHIS", "Taxable pay", "PAYE"],
        bold=True,
        colour=MUTED,
    )
    y -= 3 * mm
    rule()
    y -= 5.5 * mm
    totals = [Decimal(0)] * 5
    for month, *amounts in doc.months:
        row([month, *(money(a) for a in amounts)])
        totals = [t + a for t, a in zip(totals, amounts, strict=True)]
        y -= 6 * mm
    rule()
    y -= 5.5 * mm
    row(["Total", *(money(t) for t in totals)], bold=True)
    y -= 10 * mm
    text(left, "Rent relief allowed in the year")
    text(right, money(doc.rent_relief), align="right")
    y -= 22 * mm
    pdf.setStrokeColorRGB(*INK)
    pdf.line(left, y, left + 70 * mm, y)
    y -= 5 * mm
    text(left, "Authorised signatory", colour=MUTED)

    y = 15 * mm
    text(left, "Generated by Kxmeleon ERP from approved payroll runs.", size=8, colour=MUTED)
    pdf.showPage()
    pdf.save()
    return buffer.getvalue()
